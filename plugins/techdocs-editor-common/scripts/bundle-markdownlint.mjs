#!/usr/bin/env node
/* eslint-disable no-console */
// Gera src/vendor/markdownlint.js: o markdownlint (a versão exata do package.json) num só arquivo,
// em ESM e sem nada específico de navegador ou de Node (o -common roda nos dois: editor e action
// do Scaffolder). O pacote original usa `require` como valor em lib/resolve-module.cjs (só para
// `extends` em arquivos de configuração, que o editor não usa) e o bundler do Backstage mostra
// "Critical dependency" no overlay de desenvolvimento de quem instala o plugin. Um patch local não
// chega a quem instala pelo npm; este arquivo chega.
//
// Rodar depois de mudar a versão do markdownlint: `yarn bundle:markdownlint`. O CI confere que o
// arquivo está atualizado (`yarn bundle:markdownlint --check`).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '../src/vendor/markdownlint.js');
const require = createRequire(join(here, '../package.json'));
const { version } = JSON.parse(readFileSync(join(dirname(require.resolve('markdownlint')), '../package.json'), 'utf8'));
const wanted = JSON.parse(readFileSync(join(here, '../package.json'), 'utf8')).dependencies.markdownlint;
if (wanted !== version) {
  throw new Error(`package.json pede markdownlint ${wanted}, instalado ${version}: use a versão exata e rode yarn install`);
}

const result = await build({
  stdin: {
    contents: "export { lint } from 'markdownlint/sync';\nexport { applyFixes } from 'markdownlint';\n",
    resolveDir: join(here, '..'),
  },
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  mainFields: ['module', 'main'],
  // Os imports de Node do markdownlint (fs, os, path) na versão sem Node, que ele mesmo oferece; o
  // resto (micromark) na versão padrão, que não depende de `document`
  conditions: ['markdownlint-imports-browser', 'import', 'default'],
  target: 'es2022',
  legalComments: 'inline',
  metafile: true,
  write: false,
  plugins: [
    {
      name: 'resolve-module-browser',
      setup(b) {
        b.onLoad({ filter: /markdownlint[\\/]lib[\\/]resolve-module\.cjs$/ }, () => ({
          loader: 'js',
          contents:
            'module.exports = { resolveModule: id => { throw new Error(`Cannot load "${id}" in the browser`); } };',
        }));
      },
    },
  ],
});

// As licenças (MIT) de cada pacote embutido vão junto com o código, como elas pedem
const bundled = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  const match = input.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//);
  if (!match || bundled.has(match[1])) continue;
  const dir = join(here, '..', match[1]);
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const file = readdirSync(dir).find(name => /^licen[cs]e/i.test(name));
  bundled.set(match[1], { name: pkg.name, version: pkg.version, license: pkg.license, text: file ? readFileSync(join(dir, file), 'utf8').trim() : '' });
}
const notices = [...bundled.values()]
  .sort((a, b) => a.name.localeCompare(b.name))
  .map(p => `## ${p.name}@${p.version} (${p.license})\n\n\`\`\`text\n${p.text}\n\`\`\`\n`)
  .join('\n');
// O build (Rollup) tira comentários: as licenças vão num arquivo publicado com o pacote
const noticesFile = join(here, '../THIRD_PARTY_NOTICES.md');
const noticesText = `# Third-party notices

\`src/vendor/markdownlint.js\` bundles markdownlint@${version} and its dependencies, under these licenses.
Generated by \`scripts/bundle-markdownlint.mjs\`; do not edit by hand.

${notices}`;
const header = `/* eslint-disable */
// Gerado por scripts/bundle-markdownlint.mjs a partir de markdownlint@${version} e dependências
// (licenças em THIRD_PARTY_NOTICES.md). Não editar à mão.
`;
const code = header + result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  const current = readFileSync(out, 'utf8');
  if (current !== code || readFileSync(noticesFile, 'utf8') !== noticesText) {
    console.error('src/vendor/markdownlint.js ou THIRD_PARTY_NOTICES.md desatualizado: rode yarn bundle:markdownlint');
    process.exit(1);
  }
  console.log(`src/vendor/markdownlint.js confere com markdownlint@${version}`);
} else {
  writeFileSync(out, code);
  writeFileSync(noticesFile, noticesText);
  console.log(`src/vendor/markdownlint.js gerado de markdownlint@${version} (${code.length} bytes)`);
}
